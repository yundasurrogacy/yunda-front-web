#!/usr/bin/env node
/**
 * sync-vercel-zh-redirects.cjs
 *
 * Reads data/zh-missing-blogs.json and syncs temporary redirects into vercel.json so
 * that /zh/blog/<slug> -> /blog/<slug> for every post with no Chinese body.
 *
 * Why temporary and not permanent: the Chinese translation may be published later.
 * keeps Google willing to re-crawl and re-index the /zh/ URL once it returns,
 * whereas a permanent redirect signals a lasting merge. Vercel currently emits
 * HTTP 307 when `permanent` is false.
 *
 * Safety model: this script owns ONLY the entries it previously generated. It
 * tracks them in the `_managedZhRedirects` key inside vercel.json, so
 * hand-written redirects are never removed. If a generated redirect would
 * collide with a hand-written `source`, the hand-written one wins and the
 * collision is reported.
 *
 * If the manifest reports signalReliable: false (blog API was unreachable at
 * generation time), no redirects are written and existing managed entries are
 * left untouched — refusing to act is safer than redirecting healthy pages.
 */
const fs = require('node:fs')
const path = require('node:path')
const process = require('node:process')

const VERCEL_CONFIG_PATH = path.join(process.cwd(), 'vercel.json')
const ZH_MISSING_PATH = path.join(process.cwd(), 'data', 'zh-missing-blogs.json')
const LEGACY_MANAGED_KEY = '_managedZhRedirects'

/**
 * The ledger of redirects this script owns lives OUTSIDE vercel.json.
 * Vercel's config schema declares `additionalProperties: false`, so an unknown
 * top-level key such as `_managedZhRedirects` can get the whole config
 * rejected at deploy time. Keep vercel.json strictly schema-valid.
 *
 * Must be committed alongside vercel.json: without it the next run cannot tell
 * generated entries from hand-written ones and would leave stale redirects.
 */
const MANAGED_LEDGER_PATH = path.join(process.cwd(), 'data', 'vercel-managed-zh-redirects.json')

function fail(message) {
  console.error(`[zh-redirects] ${message}`)
  process.exit(1)
}

/**
 * Vercel compiles `redirects[].source` with path-to-regexp, where `:` starts a
 * named parameter, and `*?+(){}[]` are also structural. A slug containing any
 * of these produces either a broken pattern or a hard parse error that can
 * invalidate the whole vercel.json and fail the deploy.
 *
 * Rather than guess at an escaping scheme that Vercel does not document, fail
 * the build. Every missing Chinese route must receive the same protection;
 * silently skipping one created the previous 38-vs-37 inconsistency.
 */
const UNSAFE_SOURCE_CHARS = /[:*?+(){}[\]\\]/

function isSafeRedirectSource(source) {
  return !UNSAFE_SOURCE_CHARS.test(source)
}

function main() {
  if (!fs.existsSync(ZH_MISSING_PATH))
    fail(`Missing ${ZH_MISSING_PATH}. Run "npm run sitemap:xml" first.`)
  if (!fs.existsSync(VERCEL_CONFIG_PATH))
    fail(`Missing ${VERCEL_CONFIG_PATH}.`)

  const manifest = JSON.parse(fs.readFileSync(ZH_MISSING_PATH, 'utf8'))
  const config = JSON.parse(fs.readFileSync(VERCEL_CONFIG_PATH, 'utf8'))

  if (manifest.signalReliable === false) {
    console.warn('[zh-redirects] Manifest signalReliable=false (blog API unreachable). Leaving vercel.json unchanged.')
    return
  }

  // Read the ledger from its sidecar file, falling back to the legacy in-config
  // key so an existing vercel.json written by an older version of this script
  // is migrated rather than treated as all-hand-written.
  let previouslyManaged = new Set()
  if (fs.existsSync(MANAGED_LEDGER_PATH)) {
    const ledger = JSON.parse(fs.readFileSync(MANAGED_LEDGER_PATH, 'utf8'))
    previouslyManaged = new Set(ledger.sources || [])
  }
  else if (Array.isArray(config[LEGACY_MANAGED_KEY])) {
    previouslyManaged = new Set(config[LEGACY_MANAGED_KEY])
    console.warn(`[zh-redirects] migrating ledger out of vercel.json into ${path.relative(process.cwd(), MANAGED_LEDGER_PATH)}`)
  }
  // Never leave the non-schema key behind in vercel.json.
  delete config[LEGACY_MANAGED_KEY]

  const allRedirects = Array.isArray(config.redirects) ? config.redirects : []

  // Everything not previously generated by this script is hand-written.
  const handWritten = allRedirects.filter(r => !previouslyManaged.has(r.source))
  const handWrittenSources = new Set(handWritten.map(r => r.source))

  const desired = []
  const collisions = []
  for (const zhRoute of manifest.routes || []) {
    if (!isSafeRedirectSource(zhRoute))
      fail(`Unsafe redirect source "${zhRoute}". Fix the CMS route_id before deploying.`)
    const target = zhRoute.replace(/^\/zh/, '')
    if (handWrittenSources.has(zhRoute)) {
      collisions.push(zhRoute)
      continue
    }
    desired.push({ source: zhRoute, destination: target, permanent: false })
  }

  config.redirects = [...handWritten, ...desired]
  const managedSources = desired.map(r => r.source)

  fs.writeFileSync(VERCEL_CONFIG_PATH, `${JSON.stringify(config, null, 2)}\n`, 'utf8')
  fs.writeFileSync(MANAGED_LEDGER_PATH, `${JSON.stringify({
    note: 'Generated by scripts/sync-vercel-zh-redirects.cjs. Commit alongside vercel.json.',
    generatedAt: new Date().toISOString(),
    count: managedSources.length,
    sources: managedSources,
  }, null, 2)}\n`, 'utf8')

  // A redirect is genuinely "released" only when the route no longer appears in
  // the manifest, i.e. Chinese content was published. Routes dropped because
  // their source is unsafe, or because a hand-written rule now covers them, are
  // reported separately so the two situations are not conflated.
  const stillMissing = new Set(manifest.routes || [])
  const droppedForOtherReasons = new Set(collisions)
  const removed = [...previouslyManaged].filter(s =>
    !managedSources.includes(s)
    && !droppedForOtherReasons.has(s)
    && !stillMissing.has(s),
  )
  console.warn(`[zh-redirects] hand-written redirects preserved: ${handWritten.length}`)
  console.warn(`[zh-redirects] generated temporary redirects: ${desired.length}`)
  if (removed.length)
    console.warn(`[zh-redirects] released ${removed.length} redirect(s) (Chinese content now published): ${removed.slice(0, 5).join(', ')}${removed.length > 5 ? ' ...' : ''}`)
  if (collisions.length)
    console.warn(`[zh-redirects] WARNING ${collisions.length} route(s) already hand-written, left as-is: ${collisions.join(', ')}`)
}

main()
